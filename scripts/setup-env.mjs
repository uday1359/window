// Generates local, git-ignored .env files for server and ai-service.
// Secrets are generated randomly and never printed. Existing values are preserved
// so re-running the script does not rotate secrets unexpectedly.
// Paths are written relative to the project folder, so the configuration works for any
// Windows user and any install location (the server and AI service resolve them).
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function parseEnv(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, 'utf8').replace(/^﻿/, '').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function writeEnv(path, values, header) {
  const body = Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n');
  writeFileSync(path, `# ${header}\n# Generated by scripts/setup-env.mjs. Do not commit.\n${body}\n`, { encoding: 'utf8' });
}

/**
 * Canonical form of a path for comparison: long names instead of 8.3 short names (FINSTE~2) and
 * real casing, resolved through the deepest part that exists (the target may not exist yet).
 */
function canonical(p) {
  let head = resolve(p);
  const tail = [];
  while (!existsSync(head)) {
    const parent = dirname(head);
    if (parent === head) return resolve(p).toLowerCase();
    tail.unshift(head.slice(parent.length).replace(/^[\\/]/, ''));
    head = parent;
  }
  return join(realpathSync.native(head), ...tail).toLowerCase();
}

/** An absolute path inside the project becomes relative to it (forward slashes); others stay as they are. */
function portable(value) {
  if (!value || !isAbsolute(value)) return value;
  const rel = relative(canonical(root), canonical(value));
  return rel && !rel.startsWith('..') && !isAbsolute(rel) ? rel.replace(/\\/g, '/') : value;
}

const PATH_KEYS = ['STORAGE_DIR', 'BACKUP_DIR', 'WEB_DIST_DIR', 'TLS_PFX_FILE', 'TLS_CERT_FILE', 'TLS_KEY_FILE', 'SECRET_STORE_PATH'];
function makePortable(env) {
  for (const key of PATH_KEYS) if (env[key]) env[key] = portable(env[key]);
  return env;
}

const secret = () => randomBytes(32).toString('base64url');

const creds = parseEnv(join(root, 'server', '.env.dbcreds'));
const serverEnvPath = join(root, 'server', '.env');
const existingServer = makePortable(parseEnv(serverEnvPath));
const dbPassword = creds.DB_PASSWORD_URLENC ?? process.env.WINAGENT_DB_PASSWORD_URLENC;

if (!existingServer.DATABASE_URL && !dbPassword) {
  console.error('No database credentials found. Create server/.env.dbcreds with DB_PASSWORD_URLENC=<url-encoded password> or set DATABASE_URL in server/.env.');
  process.exit(1);
}

// On a refresh no new password is given: derive every database URL from the existing
// DATABASE_URL (same user, password, host) so none of them ends up with "undefined".
const dbUrl = (db) => {
  if (dbPassword) return `mysql://winagent:${dbPassword}@127.0.0.1:3306/${db}`;
  const u = new URL(existingServer.DATABASE_URL);
  u.pathname = `/${db}`;
  return u.toString();
};
// Drop URLs damaged by an earlier version of this script so they are regenerated.
for (const key of ['SHADOW_DATABASE_URL', 'TEST_DATABASE_URL']) {
  if (existingServer[key]?.includes(':undefined@')) delete existingServer[key];
}
// The server finds MySQL under %ProgramFiles%\MySQL by itself; keep MYSQL_BIN_DIR only when it is a
// working folder somewhere else (set on purpose), so .env stays free of machine-specific paths.
if (existingServer.MYSQL_BIN_DIR) {
  const dir = existingServer.MYSQL_BIN_DIR;
  const standard = process.env.ProgramFiles && canonical(dir).startsWith(canonical(join(process.env.ProgramFiles, 'MySQL')));
  if (standard || !existsSync(join(dir, 'mysql.exe'))) delete existingServer.MYSQL_BIN_DIR;
}
const aiToken = existingServer.AI_SERVICE_TOKEN ?? secret();

const server = {
  NODE_ENV: 'development',
  HOST: '127.0.0.1',
  PORT: '3710',
  DATABASE_URL: dbUrl('winagent'),
  SHADOW_DATABASE_URL: dbUrl('winagent_shadow'),
  TEST_DATABASE_URL: dbUrl('winagent_test'),
  AI_SERVICE_URL: 'http://127.0.0.1:8710',
  AI_SERVICE_TOKEN: aiToken,
  SESSION_TTL_HOURS: '12',
  SESSION_IDLE_MINUTES: '60',
  WEB_ORIGIN: 'http://127.0.0.1:5173',
  STORAGE_DIR: 'storage',
  BACKUP_DIR: 'backups',
  ...existingServer,
};
writeEnv(serverEnvPath, server, 'server environment');

const aiEnvPath = join(root, 'ai-service', '.env');
const existingAi = makePortable(parseEnv(aiEnvPath));
const ai = {
  AI_HOST: '127.0.0.1',
  AI_PORT: '8710',
  AI_SERVICE_TOKEN: aiToken,
  OLLAMA_URL: 'http://127.0.0.1:11434',
  SECRET_STORE_PATH: 'data/secrets.dpapi',
  ...existingAi,
};
writeEnv(aiEnvPath, ai, 'ai-service environment');

console.log('Wrote server/.env and ai-service/.env (values hidden).');
