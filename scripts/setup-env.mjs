// Generates local, git-ignored .env files for server and ai-service.
// Secrets are generated randomly and never printed. Existing values are preserved
// so re-running the script does not rotate secrets unexpectedly.
import { randomBytes } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function parseEnv(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function writeEnv(path, values, header) {
  const body = Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n');
  writeFileSync(path, `# ${header}\n# Generated by scripts/setup-env.mjs. Do not commit.\n${body}\n`, { encoding: 'utf8' });
}

const secret = () => randomBytes(32).toString('base64url');

/** Newest installed MySQL Server bin folder (8.0, 8.4, 9.x ...), for backups and restore checks. */
function mysqlBinDir() {
  const base = 'C:/Program Files/MySQL';
  const found = existsSync(base)
    ? readdirSync(base)
        .filter((d) => /^MySQL Server \d+\.\d+$/.test(d) && existsSync(join(base, d, 'bin', 'mysql.exe')))
        .sort((a, b) => parseFloat(b.split(' ')[2]) - parseFloat(a.split(' ')[2]))
    : [];
  return found.length ? `${base}/${found[0]}/bin` : `${base}/MySQL Server 8.0/bin`;
}

const creds = parseEnv(join(root, 'server', '.env.dbcreds'));
const serverEnvPath = join(root, 'server', '.env');
const existingServer = parseEnv(serverEnvPath);
const dbPassword = creds.DB_PASSWORD_URLENC ?? process.env.WINAGENT_DB_PASSWORD_URLENC;

if (!existingServer.DATABASE_URL && !dbPassword) {
  console.error('No database credentials found. Create server/.env.dbcreds with DB_PASSWORD_URLENC=<url-encoded password> or set DATABASE_URL in server/.env.');
  process.exit(1);
}

// On a refresh no new password is given: derive every database URL from the existing
// DATABASE_URL (same user, password, host) so none of them ends up with "undefined".
const dbUrl = (db) => {
  if (dbPassword) return `mysql://winagent:${dbPassword}@127.0.0.1:3306/${db}`;
  const u = new URL(existingServer.DATABASE_URL);
  u.pathname = `/${db}`;
  return u.toString();
};
// Drop URLs damaged by an earlier version of this script so they are regenerated.
for (const key of ['SHADOW_DATABASE_URL', 'TEST_DATABASE_URL']) {
  if (existingServer[key]?.includes(':undefined@')) delete existingServer[key];
}
const aiToken = existingServer.AI_SERVICE_TOKEN ?? secret();

const server = {
  NODE_ENV: 'development',
  HOST: '127.0.0.1',
  PORT: '3710',
  DATABASE_URL: dbUrl('winagent'),
  SHADOW_DATABASE_URL: dbUrl('winagent_shadow'),
  TEST_DATABASE_URL: dbUrl('winagent_test'),
  AI_SERVICE_URL: 'http://127.0.0.1:8710',
  AI_SERVICE_TOKEN: aiToken,
  SESSION_TTL_HOURS: '12',
  SESSION_IDLE_MINUTES: '60',
  WEB_ORIGIN: 'http://127.0.0.1:5173',
  STORAGE_DIR: join(root, 'storage').replace(/\\/g, '/'),
  BACKUP_DIR: join(root, 'backups').replace(/\\/g, '/'),
  MYSQL_BIN_DIR: mysqlBinDir(),
  ...existingServer,
};
writeEnv(serverEnvPath, server, 'server environment');

const aiEnvPath = join(root, 'ai-service', '.env');
const existingAi = parseEnv(aiEnvPath);
const ai = {
  AI_HOST: '127.0.0.1',
  AI_PORT: '8710',
  AI_SERVICE_TOKEN: aiToken,
  OLLAMA_URL: 'http://127.0.0.1:11434',
  SECRET_STORE_PATH: join(root, 'data', 'secrets.dpapi').replace(/\\/g, '/'),
  ...existingAi,
};
writeEnv(aiEnvPath, ai, 'ai-service environment');

console.log('Wrote server/.env and ai-service/.env (values hidden).');
